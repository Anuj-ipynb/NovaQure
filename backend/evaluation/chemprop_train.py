"""
NovaQure

Chemprop Trainer

Wrapper around the official Chemprop CLI.

Responsibilities
----------------
- Validate dataset
- Launch Chemprop training with live log streaming
- Save comprehensive metadata including the explicit artifact path
- Track and isolate the exact best.pt model artifact generated by this instance

Author:
    NovaQure Evaluation Team
"""

from __future__ import annotations

import json
import logging
import subprocess
from pathlib import Path

import pandas as pd

from backend.configs.chemprop_config import (
    DEFAULT_DATASET,
    MODEL_DIRECTORY,
    TRAINING_CONFIG_FILE,
    SMILES_COLUMN,
    TARGET_COLUMN,
    TASK_TYPE,
    TRAIN_SPLIT,
    VALIDATION_SPLIT,
    TEST_SPLIT,
    RANDOM_SEED,
    EPOCHS,
    BATCH_SIZE,
)

logger = logging.getLogger(__name__)


class ChempropTrainer:
    """
    Wrapper around the Chemprop CLI.
    """

    def __init__(
        self,
        dataset_path: Path = DEFAULT_DATASET,
    ) -> None:
        self.dataset_path = Path(dataset_path)
        self.model_path: Path | None = None

        MODEL_DIRECTORY.mkdir(
            parents=True,
            exist_ok=True,
        )

    # ---------------------------------------------------------
    # Dataset Validation
    # ---------------------------------------------------------

    def validate_dataset(self) -> None:
        """
        Validate the Chemprop dataset.
        """
        if not self.dataset_path.exists():
            raise FileNotFoundError(
                f"Dataset not found: {self.dataset_path}"
            )

        dataframe = pd.read_csv(self.dataset_path)

        expected = {
            SMILES_COLUMN,
            TARGET_COLUMN,
        }

        missing = expected - set(dataframe.columns)

        if missing:
            raise RuntimeError(
                f"Missing dataset columns: {missing}"
            )

        if dataframe.empty:
            raise RuntimeError(
                "Dataset is empty."
            )

        if dataframe[SMILES_COLUMN].isnull().any():
            raise RuntimeError(
                "Dataset contains missing SMILES."
            )

        if dataframe[TARGET_COLUMN].isnull().any():
            raise RuntimeError(
                "Dataset contains missing targets."
            )

        logger.info(
            "Validated dataset with %d molecules.",
            len(dataframe),
        )

    # ---------------------------------------------------------
    # Build Training Command
    # ---------------------------------------------------------

    def build_command(self) -> list[str]:
        """
        Build the Chemprop CLI command.
        """
        return [
            "chemprop",
            "train",
            "-i",
            str(self.dataset_path),
            "-o",
            str(MODEL_DIRECTORY),
            "-s",
            SMILES_COLUMN,
            "--target-columns",
            TARGET_COLUMN,
            "-t",
            TASK_TYPE,
            "-b",
            str(BATCH_SIZE),
            "--epochs",
            str(EPOCHS),
            "--split",
            "RANDOM",
            "--split-sizes",
            str(TRAIN_SPLIT),
            str(VALIDATION_SPLIT),
            str(TEST_SPLIT),
            "--data-seed",
            str(RANDOM_SEED),
            "--metrics",
            "rmse",
            "mae",
            "r2",
        ]

    # ---------------------------------------------------------
    # Train Model
    # ---------------------------------------------------------

    def train(self) -> None:
        """
        Launch Chemprop training. Streams logs live to stdout/stderr.
        Identifies and caches the specific best.pt model artifact created during this run.
        """
        self.validate_dataset()
        command = self.build_command()

        # Snapshot existing model artifacts before running the command
        existing_models = set(MODEL_DIRECTORY.rglob("best.pt"))

        logger.info("Starting Chemprop training...")
        logger.info("Command: %s", " ".join(command))

        try:
            import os
            # Ensure the virtual environment's bin/Scripts folder is in PATH for the subprocess
            env = os.environ.copy()
            project_root = Path(__file__).resolve().parents[2]
            venv_scripts = str(project_root / "venv" / "Scripts")
            env["PATH"] = venv_scripts + os.pathsep + env.get("PATH", "")
            
            # Resolve the absolute path to chemprop.exe if running in Windows venv
            chemprop_exe = project_root / "venv" / "Scripts" / "chemprop.exe"
            if chemprop_exe.exists():
                command[0] = str(chemprop_exe)
            
            subprocess.run(
                command,
                check=True,
                text=True,
                env=env,
            )
            logger.info("Chemprop training completed successfully.")

        except subprocess.CalledProcessError as exc:
            logger.error(
                "Chemprop training failed with exit code %d.", 
                exc.returncode
            )
            raise RuntimeError(
                "Chemprop training execution failed."
            ) from exc

        # Isolate new best.pt files generated exclusively during this run
        new_models = [
            p
            for p in MODEL_DIRECTORY.rglob("best.pt")
            if p not in existing_models
        ]

        if not new_models:
            raise FileNotFoundError(
                "Chemprop training completed but no new model artifact (best.pt) was created."
            )

        # Fallback sort by modification time if multiple version paths conflict
        new_models.sort(key=lambda p: p.stat().st_mtime, reverse=True)
        self.model_path = new_models[0]
        
        logger.info("Best model saved at %s", self.model_path)

    # ---------------------------------------------------------
    # Save Training Metadata
    # ---------------------------------------------------------

    def save_training_metadata(self) -> Path:
        """
        Save the training configuration used along with the generated model path.
        """
        metadata = {
            "dataset": str(self.dataset_path),
            "model_directory": str(MODEL_DIRECTORY),
            "model_path": str(self.model_path) if self.model_path else None,
            "task": TASK_TYPE,
            "epochs": EPOCHS,
            "batch_size": BATCH_SIZE,
            "split": {
                "train": TRAIN_SPLIT,
                "validation": VALIDATION_SPLIT,
                "test": TEST_SPLIT,
            },
            "random_seed": RANDOM_SEED,
        }

        with open(
            TRAINING_CONFIG_FILE,
            "w",
            encoding="utf-8",
        ) as file:
            json.dump(
                metadata,
                file,
                indent=4,
            )

        logger.info("Training configuration saved.")
        return TRAINING_CONFIG_FILE

    # ---------------------------------------------------------
    # Find Trained Model
    # ---------------------------------------------------------

    def find_model(self) -> Path:
        """
        Return the best.pt model artifact generated during training.
        """
        if self.model_path is None:
            raise RuntimeError(
                "No trained model available. Run training first."
            )

        return self.model_path

    # ---------------------------------------------------------
    # Run Complete Pipeline
    # ---------------------------------------------------------

    def run(self) -> Path:
        """
        Execute the full training pipeline.

        Returns
        -------
        pathlib.Path
            Path to the dynamically isolated best.pt model file.
        """
        self.train()
        self.save_training_metadata()
        model_file = self.find_model()
        
        logger.info("Pipeline completed successfully.")
        return model_file

    # ---------------------------------------------------------
    # Context Manager
    # ---------------------------------------------------------

    def __enter__(self) -> "ChempropTrainer":
        return self

    def __exit__(
        self,
        exc_type,
        exc_val,
        exc_tb,
    ) -> bool:
        # Returning False ensures exceptions are not swallowed 
        # inside the context block scope.
        return False